'use strict';
const assert=require('node:assert/strict');
const core=require('../Thunderbird_Addon/extension/core.js');
assert(core.internal('User@EXAMPLE.COM',['example.com'],true));
assert(core.internal('user@dept.example.com',['example.com'],true));
assert(!core.internal('user@dept.example.com',['example.com'],false));
assert(!core.internal('user@example.com.evil.test',['example.com'],true));
assert(!core.internal('user@notexample.com',['example.com'],true));
assert(!core.internal('invalid',['example.com'],true));
assert.deepEqual(core.domains('EXAMPLE.COM, example.com; dept.example.org'),['example.com','dept.example.org']);
assert.throws(()=>core.receiver('http://collector.example.com',false));
assert.equal(core.receiver('https://collector.example.com',false).origin,'https://collector.example.com');
assert.equal(core.permissionPattern('http://127.0.0.1:6516'),'http://127.0.0.1/*');
assert(core.outgoing({specialUse:['sent']}));assert(!core.outgoing({specialUse:['junk']}));
